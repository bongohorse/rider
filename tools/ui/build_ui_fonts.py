"""Embed the editor UI fonts (#683) as data URIs in main/editor/web/ui_fonts.js.

HTML5 custom resources are packed into the game archive, not served as files, so the
fonts travel inside a script that `html5.run` injects. Run after replacing a font:
    python tools/ui/build_ui_fonts.py          # write
    python tools/ui/build_ui_fonts.py --check  # fail if the file is stale
"""
import base64
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONTS = ROOT / "main/editor/web/fonts"
OUT = ROOT / "main/editor/web/ui_fonts.js"
FACES = [("Baloo 2", "baloo2-latin.woff2", "700 800"), ("Nunito", "nunito-latin.woff2", "800 900")]


def render() -> str:
    rules = []
    for family, name, weight in FACES:
        data = base64.b64encode((FONTS / name).read_bytes()).decode("ascii")
        rules.append(
            f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;"
            f"src:url(data:font/woff2;base64,{data}) format('woff2')}}"
        )
    css = "\\n".join(rules)
    return (
        "// Generated by tools/ui/build_ui_fonts.py from main/editor/web/fonts (SIL OFL 1.1). Do not edit.\n"
        "(()=>{if(document.getElementById('rider-ui-fonts'))return;const s=document.createElement('style');"
        f"s.id='rider-ui-fonts';s.textContent=\"{css}\";document.head.append(s);}})();\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("ui_fonts.js is stale: run python tools/ui/build_ui_fonts.py")
            return 1
        print("ui_fonts.js: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
